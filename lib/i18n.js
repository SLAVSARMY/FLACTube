let lang = 'en';

// 'ru-RU' → 'ru'; только поддержанные коды
function detect(navLang) {
  const l = String(navLang || '').toLowerCase();
  const base = l.split('-')[0];
  return ORDER.includes(base) ? base : 'en';
}

function setLang(code) {
  lang = ORDER.includes(code) ? code : 'en';
}

function autoDetect(navLang) {
  setLang(detect(navLang));
  return lang;
}

function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
  return s;
}

module.exports = { t, setLang, autoDetect, detect, ORDER, LABELS, STR, get lang() { return lang; } };
